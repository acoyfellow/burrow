import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { build } from 'esbuild';

const result = await build({
  stdin: {
    contents: `
      const raf = globalThis.requestAnimationFrame.bind(globalThis);
      globalThis.requestAnimationFrame = (cb) => {
        let done = false;
        const run = (t) => { if (!done) { done = true; cb(t); } };
        const id = raf(run);
        if (document.hidden) setTimeout(() => run(performance.now()), 50);
        return id;
      };
      export { mount } from 'cloudterm';`,
    resolveDir: process.cwd(),
    loader: 'js',
  },
  bundle: true,
  format: 'esm',
  minify: true,
  write: false,
  target: 'es2022',
});
const js = result.outputFiles[0].text;
const css = readFileSync('node_modules/cloudterm/dist/style.css', 'utf8');

writeFileSync(
  'src/ui/term.generated.ts',
  `// Generated by scripts/build-term.mjs from cloudterm. Do not edit.\nexport const TERM_VERSION = ${JSON.stringify(createHash('sha256').update(js).digest('hex').slice(0, 10))};\nexport const TERM_JS = ${JSON.stringify(js)};\nexport const TERM_CSS = ${JSON.stringify(css)};\n`,
);
console.log(`term.js ${js.length} bytes, style ${css.length} bytes`);
await import('./build-icons.mjs');
await import('./build-client.mjs');
